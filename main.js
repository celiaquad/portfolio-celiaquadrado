/* ---------------- Détection image / vidéo + rendu avec repli ---------------- */
function isVideoFile(file){ return /\.(mp4|mov|webm|ogg)$/i.test(file); }

// Construit l'élément en DOM (pas de onload/onerror en attribut : bloqués par la CSP)
function mediaEl(file, alt, opts){
  opts = opts || {};
  const missing = label => () => el.replaceWith(Object.assign(document.createElement('span'), {
    className:'missing-note', textContent: label + ' manquante : images/' + file
  }));
  let el;
  if (isVideoFile(file)){
    el = document.createElement('video');
    el.preload = 'metadata';
    if (opts.lightbox) el.controls = true;
    else { el.muted = true; el.loop = true; el.autoplay = true; el.playsInline = true; }
    el.addEventListener('error', missing('Vidéo'));
    el.src = 'images/' + file;
    return el;
  }
  el = document.createElement('img');
  el.alt = alt || '';
  el.loading = opts.lightbox ? 'eager' : 'lazy';
  if (opts.lightbox) el.fetchPriority = 'high';
  el.style.opacity = 0;
  el.style.transition = 'opacity .3s';
  el.addEventListener('load', () => { el.style.opacity = 1; });
  el.addEventListener('error', missing('Image'));
  el.src = 'images/' + file;
  return el;
}

function preloadFile(file){
  if (!file || isVideoFile(file)) return;
  new Image().src = 'images/' + file;
}

/* ---------------- Lignes de séries (Rue / Expérimental) ---------------- */
function buildRows(list, host){
  list.forEach(it => {
    const b = document.createElement('button');
    b.type = 'button';
    b.className = 'row';
    const tag = (it.slides.length > 1 ? it.slides.length + ' vues' : 'Vue unique') + '  ·  ' + it.year;
    b.innerHTML = `<span class="num">${it.num}</span><span class="title">${it.title}</span><span class="tag">${tag}</span>`;
    b.addEventListener('click', () => openLb(it, 0));
    b.addEventListener('mouseenter', () => preloadFile(it.slides[0].file), { once:true });
    b.addEventListener('focus', () => preloadFile(it.slides[0].file), { once:true });
    host.appendChild(b);
  });
}
