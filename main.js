/* ---------------- Lightbox ---------------- */
const lb = document.getElementById('lb');
let current = null, index = 0, lastFocused = null;

// Rend le reste de la page inerte pendant que la visionneuse est ouverte (piège le focus)
function setBackgroundInert(on){
  Array.from(document.body.children).forEach(el => {
    if (el !== lb && el.tagName !== 'SCRIPT') el.inert = on;
  });
}

function openLb(it, i){
  current = it; index = i;
  lastFocused = document.activeElement;
  lb.classList.add('on');
  lb.setAttribute('aria-hidden', 'false');
  setBackgroundInert(true);
  document.body.classList.add('lb-open');
  renderLb();
  document.getElementById('lb-close').focus();
  it.slides.forEach((s, idx) => { if (idx !== i) preloadFile(s.file); });
}
function closeLb(){
  current = null;
  lb.classList.remove('on');
  lb.setAttribute('aria-hidden', 'true');
  setBackgroundInert(false);
  document.body.classList.remove('lb-open');
  if (lastFocused) lastFocused.focus();
}
function step(d){
  if (!current) return;
  const t = current.slides.length;
  index = (index + d + t) % t;
  renderLb();
}
function renderLb(){
  if (!current) return;
  const s = current.slides[index];
  const multi = current.slides.length > 1;
  document.getElementById('lb-title').textContent = current.title;
  document.getElementById('lb-title2').textContent = current.title;
  document.getElementById('lb-count').textContent = multi ? (index + 1) + ' / ' + current.slides.length : '';
  const alt = current.title + (multi ? ', image ' + (index + 1) + ' sur ' + current.slides.length : '') + ' — Célia Quadrado, photographe à Lyon';
  document.getElementById('lb-media').replaceChildren(mediaEl(s.file, alt, {lightbox:true}));
  document.getElementById('lb-specs').textContent = s.specs;
  document.getElementById('lb-desc').textContent = current.desc || '';
  document.getElementById('lb-nav').style.display = multi ? 'flex' : 'none';
  if (multi) {
    const n = current.slides.length;
    preloadFile(current.slides[(index + 1) % n].file);
    preloadFile(current.slides[(index - 1 + n) % n].file);
  }
}
document.getElementById('lb-close').addEventListener('click', closeLb);
document.getElementById('lb-prev').addEventListener('click', () => step(-1));
document.getElementById('lb-next').addEventListener('click', () => step(1));
document.addEventListener('keydown', e => {
  if (!current) return;
  if (e.key === 'Escape') closeLb();
  if (e.key === 'ArrowLeft') step(-1);
  if (e.key === 'ArrowRight') step(1);
});

